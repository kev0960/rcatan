fn build_reverse_map<const N: usize>(arr: &[[u8; 6]]) -> [u8; N] {
    let mut m = [0; N];
    for (i, row) in arr.iter().enumerate() {
        for &idx in row {
            m[idx as usize] = i as u8;
        }
    }
    m
}
